import os

import uvicorn
from fastapi import FastAPI

from transfers.transfer import main_transfer

app = FastAPI(title="Transfer Service")


@app.get("/trigger")
async def trigger():
    main_transfer()

    return

if __name__ == "__main__":
    port = int(os.getenv("PORT", 8080))
    uvicorn.run(app, host="0.0.0.0", port=port)
